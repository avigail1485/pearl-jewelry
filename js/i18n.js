  const STORAGE_KEY = "tds-lang";

  function getLang() {
    return localStorage.getItem(STORAGE_KEY) || "en";
  }

  function applyLanguage(lang) {
    const strings = dict[lang] || dict.en;
    document.documentElement.setAttribute("lang", lang === "he" ? "he" : "en");
    document.documentElement.setAttribute("dir", lang === "he" ? "rtl" : "ltr");
    document.documentElement.classList.toggle("rtl", lang === "he");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (strings[key] !== undefined) el.innerHTML = strings[key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (strings[key] !== undefined) el.setAttribute("placeholder", strings[key]);
    });

    document.querySelectorAll("[data-lang-label]").forEach((el) => {
      el.textContent = strings["lang.toggle"];
    });

    localStorage.setItem(STORAGE_KEY, lang);
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  function toggleLanguage() {
    applyLanguage(getLang() === "en" ? "he" : "en");
  }

  document.addEventListener("DOMContentLoaded", () => {
    applyLanguage(getLang());
    document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
      btn.addEventListener("click", toggleLanguage);
    });
  });

  window.TDS_I18N = { applyLanguage, toggleLanguage, getLang, dict };
